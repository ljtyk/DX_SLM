"""Compare GPT-Neo 1.3B before and after the QLoRA fine-tune from SFT.py.

Run from the repository root:  python results/generate_qlora_samples.py
Downloads EleutherAI/gpt-neo-1.3B (~5 GB) on first run and needs the adapter in
sft-neo-qlora-final/ (not in the repository). Writes results/qlora_samples.md.
"""
import torch
import torch.utils._triton

# PEFT imports bitsandbytes, whose optional Triton kernels need a C compiler on
# Windows. Inference here does not use them, so report Triton as unavailable.
torch.utils._triton.has_triton = lambda: False

from peft import PeftModel
from transformers import AutoModelForCausalLM, AutoTokenizer

BASE = "EleutherAI/gpt-neo-1.3B"
ADAPTER = "sft-neo-qlora-final"
DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
MAX_NEW_TOKENS = 120

PROMPTS = [
    "Why is the sky blue?",
    "What is the capital of France?",
    "Give me a simple recipe for pancakes.",
    "Write a haiku about the ocean.",
    "What's 4+5?",
]

tokenizer = AutoTokenizer.from_pretrained(BASE)
tokenizer.pad_token = tokenizer.eos_token


def alpaca(instruction):
    # Same template as SFT.py
    return f"### Instruction:\n{instruction}\n\n### Response:\n"


def answer(model, instruction):
    inputs = tokenizer(alpaca(instruction), return_tensors="pt").to(DEVICE)
    with torch.no_grad():
        # Greedy decoding, as in SFT_run.py
        out = model.generate(**inputs, max_new_tokens=MAX_NEW_TOKENS, do_sample=False,
                             pad_token_id=tokenizer.eos_token_id)
    return tokenizer.decode(out[0][inputs["input_ids"].shape[-1]:], skip_special_tokens=True).strip()


def quote(text):
    return "\n".join("> " + line if line else ">" for line in text.splitlines()) or "> *(empty)*"


def main():
    model = AutoModelForCausalLM.from_pretrained(BASE, torch_dtype=torch.float16).to(DEVICE).eval()
    before = {p: answer(model, p) for p in PROMPTS}

    model = PeftModel.from_pretrained(model, ADAPTER).eval()
    after = {p: answer(model, p) for p in PROMPTS}

    lines = ["# QLoRA samples: GPT-Neo 1.3B before and after fine-tuning", "",
             f"Generated by `results/generate_qlora_samples.py`. Both models get the same Alpaca "
             f"prompt template used in training and decode greedily (as in `SFT_run.py`), "
             f"{MAX_NEW_TOKENS} new tokens. The base model is in fp16; the adapter is applied on top.", ""]
    for p in PROMPTS:
        lines += [f"## {p}", "", "**Base GPT-Neo 1.3B**", "", quote(before[p]), "",
                  "**After QLoRA on Alpaca**", "", quote(after[p]), ""]

    with open("results/qlora_samples.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()

"""Generate showcase samples from the pretrained and chat-fine-tuned models.

Run from the repository root:  python results/generate_samples.py
Writes results/samples.md. Needs checkpoints/latest.pt and aligned-model/,
which are not in the repository (see README).
"""
import torch
from tokenizers import Tokenizer
from transformers import GPT2Config, GPT2LMHeadModel, PreTrainedTokenizerFast, set_seed

DEVICE = "cuda" if torch.cuda.is_available() else "cpu"
SEED = 1234

tokenizer = PreTrainedTokenizerFast(
    tokenizer_object=Tokenizer.from_file("bpe_tokenizer.json"),
    pad_token="<PAD>", bos_token="<BOS>", eos_token="<EOS>",
)

# Same sampling settings as GPT2_model.py / run_interact.py.
SAMPLING = dict(do_sample=True, temperature=0.8, top_k=50, top_p=0.95,
                eos_token_id=tokenizer.eos_token_id, pad_token_id=tokenizer.pad_token_id)


def generate(model, prompt, max_new_tokens):
    set_seed(SEED)
    inputs = tokenizer(prompt, return_tensors="pt").to(DEVICE)
    with torch.no_grad():
        # Pass only input_ids/attention_mask, as the training scripts do: this tokenizer
        # also returns token_type_ids, which GPT-2 would add as extra embeddings.
        out = model.generate(input_ids=inputs["input_ids"], attention_mask=inputs["attention_mask"],
                             max_new_tokens=max_new_tokens, **SAMPLING)
    # Byte-level BPE keeps the leading space, so the continuation joins the prompt directly.
    return tokenizer.decode(out[0][inputs["input_ids"].shape[-1]:], skip_special_tokens=True)


def load_pretrained():
    # Same config as GPT2_model.py
    config = GPT2Config(
        vocab_size=tokenizer.vocab_size, n_positions=1024, n_ctx=1024,
        n_embd=768, n_layer=12, n_head=12,
        pad_token_id=tokenizer.pad_token_id,
        scale_attn_by_inverse_layer_idx=True, reorder_and_upcast_attn=True,
    )
    model = GPT2LMHeadModel(config)
    ckpt = torch.load("checkpoints/latest.pt", map_location="cpu", weights_only=False)
    model.load_state_dict(ckpt["model_state_dict"])
    return model.to(DEVICE).eval(), ckpt["global_step"]


def quote(text):
    return "\n".join("> " + line if line else ">" for line in text.splitlines()) or ">"


def main():
    lines = ["# Sample outputs", "",
             f"Generated by `results/generate_samples.py` (seed {SEED}, temperature 0.8, "
             "top-k 50, top-p 0.95). One sample per prompt, not cherry-picked.", ""]

    model, step = load_pretrained()
    n_params = sum(p.numel() for p in model.parameters())
    lines += ["## 1. Pretrained GPT-2 (Gutenberg only)", "",
              f"`checkpoints/latest.pt`, {n_params / 1e6:.0f}M parameters, "
              f"{step:,} micro-batch steps. Text continuation, 120 new tokens.", ""]
    for prompt in ["Once upon a time", "It was a dark and stormy night, and",
                   "The old sailor looked out across the harbour and said"]:
        lines += [f"**Prompt:** {prompt}", "", quote(prompt + generate(model, prompt, 120)), ""]
    del model
    torch.cuda.empty_cache()

    model = GPT2LMHeadModel.from_pretrained("aligned-model").to(DEVICE).eval()
    lines += ["## 2. Chat fine-tuned (`aligned-model/`)", "",
              "The pretrained model above after `SFT_train.py`. Prompted in the "
              "`Human: ...\\n\\nAssistant:` format used by `run_interact.py`, 150 new tokens.", ""]
    for q in ["Why is the sky blue?", "What is the capital of France?",
              "Can you give me a simple recipe for pancakes?",
              "Tell me a short story about a dragon.",
              "What should I do if I can't sleep at night?"]:
        answer = generate(model, f"Human: {q}\n\nAssistant:", 150).strip()
        lines += [f"**Human:** {q}", "", quote("**Assistant:** " + answer), ""]

    with open("results/samples.md", "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
